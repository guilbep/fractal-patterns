// Writes src/palettes-data.ts: the curated palettes, computed once here so the page does no OKLCH math at start.
// palettes.test.ts checks the file against makePalette, so it cannot drift from PALETTE_SPECS.
import { writeFileSync } from 'node:fs';
import { PALETTE_SPECS, makePalette } from '../src/palettes.ts';

const rows = PALETTE_SPECS.map(makePalette).map((p) => `  { name: ${JSON.stringify(p.name)}, colors: ${JSON.stringify(p.colors)} },`);
writeFileSync(
  new URL('../src/palettes-data.ts', import.meta.url),
  `// Generated by scripts/make-palettes.ts (make palettes). Do not edit.\nimport type { Palette } from './palettes.ts';\n\nexport const PALETTE_DATA: readonly Palette[] = [\n${rows.join('\n')}\n];\n`,
);
